numero1 = float(input("Digite um número:").replace(",", "."))
numero2 = float(input("Digite outro número:").replace(",", "."))
soma = numero1 + numero2
print(f"{numero1} + {numero2} = {soma}")
subtracao = numero1 - numero2
print(f"{numero1} - {numero2} = {subtracao}")
multiplicacao = numero1 * numero2
print(f"{numero1} * {numero2} = {multiplicacao}")
divisao = numero1 / numero2
print(f"{numero1} / {numero2} = {divisao}")
exponente = numero1 ** numero2
print(f"{numero1} elevado a {numero2} = {exponente}")
raiz = numero1 ** (1/numero2)
print(f"raiz {numero2} de {numero1} = {raiz}")


